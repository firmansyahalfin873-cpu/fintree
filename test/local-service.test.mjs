import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { Wallet } from 'ethers';
import { openLocalDatabase } from '../src/storage/local-database.mjs';
import { createApp } from '../src/server/app.mjs';
import { createLocalNodeServer } from '../src/server/node-server.mjs';
import { loadTestnetAssets } from '../src/server/testnet-assets.mjs';

async function availablePort() {
  const server = net.createServer();
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  const { port } = server.address();
  await new Promise((resolve) => server.close(resolve));
  return port;
}

test('local service persists merchant, credentials and invoices across a restart', { timeout: 60000 }, async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fintree-service-'));
  const dbDir = path.join(dir, 'nested', 'state');
  t.after(() => { if (!path.resolve(dir).startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Unsafe cleanup path'); fs.rmSync(dir, { recursive: true, force: true }); });
  const port = await availablePort(), origin = `http://127.0.0.1:${port}`, wallet = Wallet.createRandom(), signer = Wallet.createRandom();
  const config = { chainId: 1337n, contract: Wallet.createRandom().address, token: Wallet.createRandom().address, signerAddress: signer.address, tokenDecimals: 6, feeBps: 30, ttlSeconds: 900 };
  const assets = await loadTestnetAssets();
  let db = await openLocalDatabase(dbDir);
  let web = createLocalNodeServer({ app: createApp({ db, signer, config, origin, assets }), port });
  await web.listen();
  const page = await fetch(origin);
  assert.equal(page.status, 200);
  assert.match(page.headers.get('content-security-policy'), /default-src 'self'/);
  assert.match(await page.text(), /Money moves/);
  assert.match(await (await fetch(`${origin}/dashboard`)).text(), /Connect wallet/);
  assert.equal((await fetch(`${origin}/landing.css`)).status, 200);
  assert.match(await (await fetch(`${origin}/developers`)).text(), /Create a checkout session/);
  assert.match((await fetch(`${origin}/developers.js`)).headers.get('content-type'), /javascript/);
  assert.match((await fetch(`${origin}/site-nav.js`)).headers.get('content-type'), /javascript/);
  assert.match((await fetch(`${origin}/workspace-nav.js`)).headers.get('content-type'), /javascript/);
  assert.match(await (await fetch(`${origin}/help`)).text(), /How can we help/);
  assert.match((await fetch(`${origin}/help.js`)).headers.get('content-type'), /javascript/);
  assert.match(await (await fetch(`${origin}/security`)).text(), /Payment verification/);
  assert.match(await (await fetch(`${origin}/pricing`)).text(), /Try the numbers/);
  assert.match((await fetch(`${origin}/pricing.js`)).headers.get('content-type'), /javascript/);
  assert.match((await fetch(`${origin}/landing.js`)).headers.get('content-type'), /javascript/);
  assert.match(await (await fetch(`${origin}/pay/0x${'a'.repeat(64)}`)).text(), /Connect wallet/);
  assert.equal((await fetch(`${origin}/testnet.js`)).status, 200);
  assert.equal((await fetch(`${origin}/src/auth/api-keys.mjs`)).status, 404);
  const post = (url, value, headers = {}) => fetch(`${origin}${url}`, { method: 'POST', headers: { origin, 'content-type': 'application/json', ...headers }, body: JSON.stringify(value) });
  assert.equal((await post('/api/v1/wallet/challenge', { wallet: wallet.address }, { origin: 'https://attacker.invalid' })).status, 403);
  const challenge = await (await post('/api/v1/wallet/challenge', { wallet: wallet.address })).json();
  const response = await post('/api/v1/wallet/complete', { id: challenge.id, nonce: challenge.nonce, signature: await wallet.signMessage(challenge.message) });
  assert.equal(response.status, 201);
  const { apiKey } = await response.json();
  const settings = await post('/api/v1/merchant', { businessName: '  Toko Contoh  ' }, { authorization: `Bearer ${apiKey}` });
  assert.equal((await settings.json()).businessName, 'Toko Contoh');
  assert.equal((await post('/api/v1/merchant', { businessName: 'Bad\nName' }, { authorization: `Bearer ${apiKey}` })).status, 400);
  const create = await post('/api/v1/checkout/sessions', { orderId: 'persistent-order', amount: '5', feePayer: 'customer' }, { authorization: `Bearer ${apiKey}`, 'idempotency-key': 'persistent-key' });
  assert.equal(create.status, 201);
  const session = await create.json();
  assert.equal(session.checkoutUrl, `${origin}/pay/${session.id}`);
  await new Promise((resolve) => web.server.close(resolve));
  await db.close();
  db = await openLocalDatabase(dbDir);
  web = createLocalNodeServer({ app: createApp({ db, signer, config, origin, assets }), port });
  await web.listen();
  const recovered = await fetch(`${origin}/api/v1/checkout/sessions/${session.id}`, { headers: { authorization: `Bearer ${apiKey}` } });
  assert.equal(recovered.status, 200);
  assert.equal((await recovered.json()).orderId, 'persistent-order');
  assert.equal((await (await fetch(`${origin}/api/v1/merchant`, { headers: { authorization: `Bearer ${apiKey}` } })).json()).businessName, 'Toko Contoh');
  const publicResponse = await fetch(`${origin}/api/v1/public/checkout/sessions/${session.id}`);
  const publicSession = await publicResponse.json();
  assert.equal(publicSession.id, session.id);
  assert.equal(publicSession.businessName, 'Toko Contoh');
  assert.equal((await fetch(`${origin}/pay/${session.id}`)).status, 200);
  await new Promise((resolve) => web.server.close(resolve));
  await db.query("update fintree_private.schema_version set checksum='unexpected' where version=1");
  await db.close();
  await assert.rejects(openLocalDatabase(dbDir), /manual review is required/);
});
