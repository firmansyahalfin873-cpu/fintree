import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { Wallet } from 'ethers';
import { issueApiKey } from '../src/auth/api-keys.mjs';
import { createApp } from '../src/server/app.mjs';
import { FintreeClient } from '../src/sdk/index.mjs';

test('merchants can list, issue and revoke only their own API keys', async (t) => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(fs.readFileSync('db/schema-draft.sql', 'utf8'));
  await db.exec(fs.readFileSync('db/local-migrations/003-checkout-details.sql', 'utf8'));
  const a = '00000000-0000-0000-0000-000000000001', b = '00000000-0000-0000-0000-000000000002';
  await db.query('insert into fintree_private.merchants (id,wallet_address,business_name) values ($1,$2,$3),($4,$5,$6)', [a, Wallet.createRandom().address.toLowerCase(), 'A', b, Wallet.createRandom().address.toLowerCase(), 'B']);
  const first = await issueApiKey(db, a), other = await issueApiKey(db, b), signer = Wallet.createRandom();
  const origin = 'http://127.0.0.1:4174';
  const config = { chainId: 1337n, contract: Wallet.createRandom().address, token: Wallet.createRandom().address, signerAddress: signer.address, tokenDecimals: 6, feeBps: 30, ttlSeconds: 900 };
  const app = createApp({ db, signer, config, origin });
  const request = (path, key, method = 'GET', extra = {}) => app(new Request(`${origin}${path}`, { method, headers: { authorization: `Bearer ${key}`, ...extra } }));
  assert.equal((await request('/api/v1/api-keys', 'invalid')).status, 401);
  const listResponse = await request('/api/v1/api-keys', first.key);
  assert.equal(listResponse.headers.get('cache-control'), 'no-store');
  const list = await listResponse.json();
  assert.equal(list.data.length, 1);
  assert.equal(list.data[0].current, true);
  assert.equal(JSON.stringify(list).includes(first.key), false);
  assert.equal(JSON.stringify(list).includes('key_hash'), false);
  assert.equal((await request(`/api/v1/api-keys/${first.id}`, other.key, 'DELETE')).status, 404);
  assert.equal((await request(`/api/v1/api-keys/${other.id}`, first.key, 'DELETE', { origin: 'https://attacker.invalid' })).status, 403);
  assert.equal((await request('/api/v1/api-keys/not-a-uuid', first.key, 'DELETE')).status, 404);
  const sdk = new FintreeClient({ apiKey: first.key, baseUrl: `${origin}/`, fetchImpl: (url, options) => app(new Request(url, options)) });
  const created = await sdk.createApiKey();
  assert.match(created.key, /^fintree_test_[0-9a-f]{64}$/);
  assert.equal((await sdk.listApiKeys()).data.length, 2);
  assert.equal((await sdk.revokeApiKey(created.id)).revoked, true);
  assert.equal((await request('/api/v1/api-keys', created.key)).status, 401);
  await db.query(`insert into fintree_private.api_keys (id,merchant_id,key_hash,key_prefix)
    select gen_random_uuid(),$1,lpad(to_hex(n),64,'0'),'old-' || n from generate_series(1,55) n`, [a]);
  const page1 = await sdk.listApiKeys();
  assert.equal(page1.data.length, 50);
  assert.ok(page1.nextCursor);
  const page2 = await sdk.listApiKeys({ startingAfter: page1.nextCursor });
  assert.equal(page2.data.length, 7);
  assert.equal(new Set([...page1.data, ...page2.data].map((entry) => entry.id)).size, 57);
  assert.equal((await request(`/api/v1/api-keys?starting_after=${other.id}`, first.key)).status, 400);
  const revoked = await request(`/api/v1/api-keys/${first.id}`, first.key, 'DELETE');
  assert.deepEqual(await revoked.json(), { revoked: true, current: true });
  assert.equal((await request('/api/v1/api-keys', first.key)).status, 401);
  assert.equal((await request('/api/v1/api-keys', other.key)).status, 200);
});
