import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { Wallet, verifyTypedData } from 'ethers';
import { PGlite } from '@electric-sql/pglite';
import { createCheckoutSession, getMerchantCheckoutSession, IdempotencyConflict } from '../src/payments/checkout-sessions.mjs';
import { QUOTE_TYPES } from '../src/payments/create-quote.mjs';
import { createPublicCheckoutHandler } from '../src/api/public-checkout-handler.mjs';

test('checkout creation stores a valid quote and handles retries and merchant isolation', async (t) => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(fs.readFileSync('db/schema-draft.sql', 'utf8'));
  await db.exec(fs.readFileSync('db/local-migrations/003-checkout-details.sql', 'utf8'));
  const merchantId = '00000000-0000-0000-0000-000000000001';
  const otherId = '00000000-0000-0000-0000-000000000002';
  const signer = Wallet.createRandom();
  const merchant = Wallet.createRandom().address;
  const other = Wallet.createRandom().address;
  await db.query('insert into fintree_private.merchants (id,wallet_address,business_name) values ($1,$2,$3),($4,$5,$6)', [merchantId, merchant.toLowerCase(), 'One', otherId, other.toLowerCase(), 'Two']);
  const config = { chainId: 84532n, contract: Wallet.createRandom().address, token: Wallet.createRandom().address, signerAddress: signer.address, tokenDecimals: 6, feeBps: 30, ttlSeconds: 900 };
  const request = { amount: '10.000000', orderId: 'order-1', feePayer: 'customer' };
  const create = (args = {}) => createCheckoutSession({ db, signer, config, merchantId, idempotencyKey: 'key-1', request, ...args });
  const [first, second] = await Promise.all([create(), create()]);
  assert.equal(Number(first.created) + Number(second.created), 1);
  assert.deepEqual(first.session, second.session);
  assert.equal(first.session.totalPayable, '10030000');
  const session = first.session;
  const recovered = verifyTypedData({ name: 'Fintree', version: '1', chainId: config.chainId, verifyingContract: config.contract }, QUOTE_TYPES,
    { invoiceId: session.id, token: session.token, merchant: session.merchant, merchantAmount: session.merchantAmount, protocolFee: session.protocolFee, deadline: session.deadline }, session.signature);
  assert.equal(recovered, signer.address);
  assert.deepEqual((await create({ request: { ...request, amount: '10' } })).session, session);
  await assert.rejects(create({ request: { ...request, amount: '11' } }), IdempotencyConflict);
  await assert.rejects(create({ request: { ...request, orderId: 'other' } }), IdempotencyConflict);
  assert.deepEqual(await getMerchantCheckoutSession(db, merchantId, session.id), session);
  assert.equal(await getMerchantCheckoutSession(db, otherId, session.id), null);
  assert.notEqual((await create({ merchantId: otherId })).session.id, session.id);
  await assert.rejects(create({ idempotencyKey: 'bad key' }), TypeError);
  await assert.rejects(create({ idempotencyKey: 'new', request: { ...request, amount: '1.0000001' } }), RangeError);
  assert.equal((await db.query('select count(*)::int as count from fintree_private.invoices')).rows[0].count, 2);
  const withDetails = { ...request, returnUrl: 'https://merchant.example/thanks', metadata: { customer: 'private', campaign: 'spring' } };
  const extra = await create({ idempotencyKey: 'details', request: withDetails });
  assert.deepEqual(extra.session.metadata, { campaign: 'spring', customer: 'private' });
  assert.equal(extra.session.returnUrl, 'https://merchant.example/thanks');
  const publicResponse = await createPublicCheckoutHandler({ db })(new Request(`http://localhost/api/v1/public/checkout/sessions/${extra.session.id}`));
  const publicData = await publicResponse.json();
  assert.equal(publicData.returnUrl, 'https://merchant.example/thanks');
  assert.equal(Object.hasOwn(publicData, 'metadata'), false);
  assert.equal(JSON.stringify(publicData).includes('private'), false);
  assert.equal((await create({ idempotencyKey: 'details', request: { ...withDetails, metadata: { campaign: 'spring', customer: 'private' } } })).session.id, extra.session.id);
  await assert.rejects(create({ idempotencyKey: 'details', request: { ...withDetails, metadata: { customer: 'changed' } } }), IdempotencyConflict);
  await assert.rejects(create({ idempotencyKey: 'invalid-url', request: { ...request, returnUrl: 'javascript:alert(1)' } }), TypeError);
  await assert.rejects(create({ idempotencyKey: 'invalid-meta', request: { ...request, metadata: { private: { nested: 'no' } } } }), TypeError);
});
