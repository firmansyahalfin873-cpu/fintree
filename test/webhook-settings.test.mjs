import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { randomBytes } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { Wallet } from 'ethers';
import { issueApiKey } from '../src/auth/api-keys.mjs';
import { createApp } from '../src/server/app.mjs';
import { createWebhookSettings } from '../src/webhooks/settings.mjs';
import { createCheckoutSession } from '../src/payments/checkout-sessions.mjs';
import { deliverNextWebhook } from '../src/webhooks/deliver-next.mjs';
import { verifyWebhook } from '../src/webhooks/signature.mjs';
import { FintreeClient } from '../src/sdk/index.mjs';

test('webhook settings encrypt secrets, isolate merchants and queue delivery only when configured', { timeout: 60000 }, async (t) => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(fs.readFileSync('db/schema-draft.sql', 'utf8'));
  await db.exec(fs.readFileSync('db/local-migrations/003-checkout-details.sql', 'utf8'));
  await db.exec(fs.readFileSync('db/local-migrations/002-merchant-updated-at.sql', 'utf8'));
  const a = '00000000-0000-0000-0000-000000000001', b = '00000000-0000-0000-0000-000000000002';
  await db.query('insert into fintree_private.merchants (id,wallet_address,business_name) values ($1,$2,$3),($4,$5,$6)', [a, Wallet.createRandom().address.toLowerCase(), 'A', b, Wallet.createRandom().address.toLowerCase(), 'B']);
  const keyA = await issueApiKey(db, a), keyB = await issueApiKey(db, b), masterKey = randomBytes(32);
  const settings = createWebhookSettings({ db, masterKey });
  const signer = Wallet.createRandom(), origin = 'http://127.0.0.1:4174';
  const config = { chainId: 1337n, contract: Wallet.createRandom().address, token: Wallet.createRandom().address, signerAddress: signer.address, tokenDecimals: 6, feeBps: 30, ttlSeconds: 900 };
  const app = createApp({ db, signer, config, origin, webhookSettings: settings });
  const change = await app(new Request(`${origin}/api/v1/merchant`, { method: 'POST', headers: { authorization: `Bearer ${keyA.key}`, 'content-type': 'application/json' }, body: JSON.stringify({ businessName: 'Merchant A' }) }));
  assert.equal(change.status, 200);
  const otherProfile = await app(new Request(`${origin}/api/v1/merchant`, { headers: { authorization: `Bearer ${keyB.key}` } }));
  assert.equal((await otherProfile.json()).businessName, 'B');
  const injected = await app(new Request(`${origin}/api/v1/merchant`, { method: 'POST', headers: { authorization: `Bearer ${keyA.key}`, 'content-type': 'application/json' }, body: JSON.stringify({ businessName: 'Changed', merchantId: b }) }));
  assert.equal(injected.status, 400);
  const call = (key, method = 'GET', body) => app(new Request(`${origin}/api/v1/webhook`, { method, headers: { authorization: `Bearer ${key}`, ...(body ? { 'content-type': 'application/json', origin } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }));
  assert.equal((await call('invalid')).status, 401);
  assert.deepEqual(await (await call(keyA.key)).json(), { configured: false });
  assert.equal((await call(keyA.key, 'POST', { url: 'http://127.0.0.1/' })).status, 400);
  const configured = await call(keyA.key, 'POST', { url: 'https://merchant.example/hook' });
  assert.equal(configured.status, 200);
  const { secret, url } = await configured.json();
  assert.match(secret, /^whsec_[0-9a-f]{64}$/);
  const row = (await db.query('select * from fintree_private.webhook_settings where merchant_id=$1', [a])).rows[0];
  assert.equal(JSON.stringify(row).includes(secret), false);
  assert.deepEqual(await settings.getForDelivery(a), { url, secret });
  assert.equal((await (await call(keyA.key)).json()).secret, undefined);
  assert.deepEqual(await (await call(keyB.key)).json(), { configured: false });
  await assert.rejects(createWebhookSettings({ db, masterKey: randomBytes(32) }).assertKey());
  await db.query("update fintree_private.webhook_settings set destination_url='https://other.example/' where merchant_id=$1", [a]);
  await assert.rejects(settings.getForDelivery(a));
  await db.query('update fintree_private.webhook_settings set destination_url=$2 where merchant_id=$1', [a, url]);
  const makeInvoice = (merchantId, idempotencyKey) => createCheckoutSession({ db, signer, config, merchantId, idempotencyKey, request: { amount: '1', orderId: idempotencyKey, feePayer: 'customer' } });
  const invoiceA = (await makeInvoice(a, 'a')).session, invoiceB = (await makeInvoice(b, 'b')).session;
  await db.query(`insert into fintree_private.webhook_outbox (event_id,invoice_id,event_type,payload,next_attempt_at) values
    ('evt_a',$1,'checkout.session.completed',$2::jsonb,now()),('evt_b',$3,'checkout.session.completed',$4::jsonb,now()-interval '1 minute')`,
  [invoiceA.id, JSON.stringify({ id: 'evt_a', type: 'checkout.session.completed' }), invoiceB.id, JSON.stringify({ id: 'evt_b', type: 'checkout.session.completed' })]);
  let unblock, claimed;
  const waiting = new Promise((resolve) => { unblock = resolve; });
  const started = new Promise((resolve) => { claimed = resolve; });
  const worker = { db, configuredOnly: true, getDeliveryConfig: (merchantId) => settings.getForDelivery(merchantId) };
  assert.equal((await deliverNextWebhook({ ...worker, transport: async () => ({ status: 503 }) })).status, 'retry');
  await db.query("update fintree_private.webhook_outbox set next_attempt_at=now() where event_id='evt_a'");
  const first = deliverNextWebhook({ ...worker, transport: async ({ body, headers }) => { assert.equal(verifyWebhook(body, headers['x-fintree-signature'], secret), true); claimed(); await waiting; return { status: 204 }; } });
  await started;
  assert.equal((await deliverNextWebhook({ ...worker, transport: async () => ({ status: 200 }) })).status, 'idle');
  unblock();
  assert.equal((await first).status, 'delivered');
  const attempts = await app(new Request(`${origin}/api/v1/webhook/attempts`, { headers: { authorization: `Bearer ${keyA.key}` } }));
  assert.deepEqual((await attempts.json()).data.map((entry) => entry.eventId), ['evt_a', 'evt_a']);
  const otherAttempts = await app(new Request(`${origin}/api/v1/webhook/attempts`, { headers: { authorization: `Bearer ${keyB.key}` } }));
  assert.equal((await otherAttempts.json()).data.length, 0);
  assert.equal((await db.query("select status from fintree_private.webhook_outbox where event_id='evt_b'")).rows[0].status, 'pending');
  const rotated = await (await call(keyA.key, 'POST', { url })).json();
  assert.notEqual(rotated.secret, secret);
  assert.equal((await settings.getForDelivery(a)).secret, rotated.secret);
  const sdk = new FintreeClient({ apiKey: keyA.key, baseUrl: `${origin}/`, fetchImpl: (destination, options) => app(new Request(destination, options)) });
  assert.equal((await sdk.getWebhookSettings()).url, url);
  assert.equal((await sdk.listWebhookAttempts()).data.length, 2);
  await db.query(`insert into fintree_private.webhook_outbox (event_id,invoice_id,event_type,payload) values ('evt_manual',$1,'test.manual',$2::jsonb)`,
    [invoiceA.id, JSON.stringify({ id: 'evt_manual', type: 'test.manual' })]);
  assert.equal((await deliverNextWebhook({ ...worker, maxAttempts: 1, transport: async () => ({ status: 503 }) })).status, 'failed');
  assert.equal((await sdk.listWebhookAttempts()).data.find((entry) => entry.eventId === 'evt_manual').retryable, true);
  const retryPath = `${origin}/api/v1/webhook/events/evt_manual/retry`;
  assert.equal((await app(new Request(retryPath, { method: 'POST', headers: { authorization: `Bearer ${keyB.key}` } }))).status, 404);
  assert.equal((await app(new Request(`${origin}/api/v1/webhook/events/evt_a/retry`, { method: 'POST', headers: { authorization: `Bearer ${keyA.key}` } }))).status, 404);
  assert.deepEqual(await sdk.retryWebhook('evt_manual'), { queued: true });
  await assert.rejects(sdk.retryWebhook('evt_manual'));
  assert.equal((await deliverNextWebhook({ ...worker, maxAttempts: 2, transport: async () => ({ status: 503 }) })).status, 'retry');
  await db.query("update fintree_private.webhook_outbox set next_attempt_at=now() where event_id='evt_manual'");
  assert.equal((await deliverNextWebhook({ ...worker, maxAttempts: 2, transport: async () => ({ status: 204 }) })).status, 'delivered');
  const history = (await db.query("select attempt_number,outcome from fintree_private.webhook_attempts where event_id='evt_manual' order by attempt_number")).rows;
  assert.deepEqual(history.map((entry) => [entry.attempt_number, entry.outcome]), [[1, 'failed'], [2, 'retry'], [3, 'delivered']]);
});
